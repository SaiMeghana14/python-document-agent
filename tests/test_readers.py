from pathlib import Path

import pytest

from document_agent.readers import (
    NoExtractableTextError,
    UnsupportedFileError,
    read_csv_file,
    read_document,
)


def test_reads_text_file(tmp_path: Path):
    path = tmp_path / "notes.txt"
    path.write_text("Hello document library", encoding="utf-8")
    assert "Hello" in read_document(path).text


def test_reads_markdown_file(tmp_path: Path):
    path = tmp_path / "notes.md"
    path.write_text("# Heading", encoding="utf-8")
    assert "Heading" in read_document(path).text


def test_reads_csv_headers_and_rows(tmp_path: Path):
    path = tmp_path / "data.csv"
    path.write_text("code,name\n001,Ana\n", encoding="utf-8")
    result = read_csv_file(path)
    assert result.csv_headers == ["code", "name"]
    assert result.csv_rows == [["001", "Ana"]]


def test_rejects_malformed_csv(tmp_path: Path):
    path = tmp_path / "bad.csv"
    path.write_text("a,b\n1,2,3\n", encoding="utf-8")
    with pytest.raises(ValueError, match="Malformed CSV"):
        read_csv_file(path)


def test_image_is_reported_as_unsupported(tmp_path: Path):
    path = tmp_path / "photo.png"
    path.write_bytes(b"not really an image")
    with pytest.raises(UnsupportedFileError, match="Image files are not supported"):
        read_document(path)


def test_no_text_pdf_message(tmp_path: Path):
    # A minimal valid blank PDF generated by pypdf.
    from pypdf import PdfWriter

    path = tmp_path / "blank.pdf"
    writer = PdfWriter()
    writer.add_blank_page(width=72, height=72)
    with path.open("wb") as file:
        writer.write(file)
    with pytest.raises(NoExtractableTextError, match="OCR may be needed"):
        read_document(path)
